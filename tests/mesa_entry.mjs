import assert from 'node:assert/strict';
import {entryRoute,materialURL} from '../prototipo/mesa/entry.js';
assert.equal(entryRoute(''),null);
assert.deepEqual(entryRoute('','?ambiente=local'),{kind:'task',route:'mesa'});
assert.equal(entryRoute('','?ambiente=local&documento=showtrials-1665&idioma=en').id,'showtrials-1665');
assert.deepEqual(entryRoute('#/doc/showtrials-1665?idioma=ru'),{kind:'document',id:'showtrials-1665',language:'ru',project:'',mode:'read'});
assert.equal(entryRoute('#/doc/id?editar=1').mode,'edit');
assert.equal(entryRoute('#/estudo/id').mode,'paragraphs');
assert.equal(entryRoute('#/estudo/id?modo=paralelo').mode,'parallel');
assert.equal(entryRoute('#/bancada?projeto=project-123').route,'projetos/project-123');
assert.deepEqual(entryRoute('#/colecao/alpha/subcolecao/investigacao?pagina=2'),{kind:'library',collection:'alpha',sub:'investigacao',page:2});
assert.equal(entryRoute('#/busca?q=%D0%9A%D0%BE%D1%80%D0%BA').q,'Корк');
assert.equal(entryRoute('#/markdown/id%3Aen').language,'en');
assert.equal(entryRoute('#/markdown/id%3Aen').mode,'edit');
assert.equal(entryRoute('#/importar?documento=id').mode,'import-translation');
assert.equal(entryRoute('#/documento/id').route,'catalogo/id');
assert.equal(entryRoute('#/colecoes','?ambiente=local').route,'colecoes');
assert.equal(entryRoute('#/colecoes').route,'biblioteca');
assert.equal(entryRoute('#/pdf/pdf-123?pagina=4').page,4);
assert.equal(entryRoute('#catalogo/id'),null);
const material={kind:'document',doc:{id:'showtrials-1665'},lang:'en',mode:'parallel',projectId:'project-123'};
const entry=entryRoute(materialURL(material));
assert.equal(entry.id,material.doc.id);assert.equal(entry.language,'en');assert.equal(entry.mode,'parallel');assert.equal(entry.project,material.projectId);
assert.equal(entryRoute(materialURL({kind:'pdf',backendSource:'pdf-123',page:2})).page,2);
assert.equal(materialURL({kind:'pdf',file:{}}),'#mesa');
// Recursos devem resolver sob o prefixo do repositório, não na raiz do domínio.
const root=new URL('https://example.github.io/documentos-sovieticos/');
const app=new URL('prototipo/mesa/app.js',root);
assert.equal(new URL('../../data/manifest.json',app).pathname,'/documentos-sovieticos/data/manifest.json');
assert.equal(new URL('../../',new URL('prototipo/mesa/',root)).href,root.href);
console.log('OK: URLs de documentos, idiomas, projetos, fontes, coleções, editoria e subdiretório GitHub Pages.');
